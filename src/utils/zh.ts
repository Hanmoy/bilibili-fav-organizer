/** 繁体转简体（按字符查表） */
export function toSimplified(s: string): string {
  let out = '';
  for (const ch of s) out += SIMPLE_MAP[ch] || ch;
  return out;
}

/** 归一化：简体 + 小写 + 去空白与常见标点（用于名称对比） */
export function normalizeName(s: string): string {
  return toSimplified(s)
    .toLowerCase()
    .replace(/[\s\u3000]+/g, '')
    .replace(/[，。！？、；：""''（）()【】\[\]《》〈〉·\-—_/\\|.,!?;:'"`~@#$%^&*+=<>]/g, '');
}

/**
 * 把「新分类名」尽量匹配到已有收藏夹（繁简/近义）
 * 返回 { matched: Map<newName, existingName>, unmatched: string[] }
 * 匹配规则：归一化后完全相等；或一方包含另一方且长度 ≥ 2
 */
export function matchExistingFolders(newNames: string[], existingFolders: string[]): { matched: Map<string, string>; unmatched: string[] } {
  const existingNorm = existingFolders.map((n) => ({ orig: n, norm: normalizeName(n) }));
  const matched = new Map<string, string>();
  const unmatched: string[] = [];

  for (const name of newNames) {
    const norm = normalizeName(name);
    if (!norm) { unmatched.push(name); continue; }
    // 1) 完全相等
    let hit = existingNorm.find((e) => e.norm === norm);
    // 2) 包含关系（长度 ≥ 2，避免单字误匹配）
    if (!hit) {
      hit = existingNorm.find(
        (e) => e.norm.length >= 2 && norm.length >= 2 && (e.norm.includes(norm) || norm.includes(e.norm)),
      );
    }
    if (hit) matched.set(name, hit.orig);
    else unmatched.push(name);
  }
  return { matched, unmatched };
}
